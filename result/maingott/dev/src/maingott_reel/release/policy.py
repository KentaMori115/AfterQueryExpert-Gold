"""Production readiness.

``validate`` asks whether the Reel is a valid file that says what it was
approved to say. This asks a narrower and harder question: may these exact
bytes leave the building?

The difference is inputs a human signed off on. A Reel assembled from
placeholder footage, spoken by a voice nobody approved, or stamped with a logo
that is not in the brand registry is a perfectly valid file and an
unacceptable advertisement. Those are release gates, not quality gates — Phase
6's semantics are left exactly as they were.
"""

from __future__ import annotations

from pathlib import Path

from maingott_reel.config import Settings
from maingott_reel.models import (
    ApprovalRecord,
    ArtifactFingerprint,
    AssetSource,
    AssetType,
    BrandRegistry,
    GateGroup,
    GateSeverity,
    QualityGate,
    QualityReport,
    ReviewChecklist,
    StageName,
    VoiceProfile,
)
from maingott_reel.release.brand import check_asset
from maingott_reel.release.inputs import ReleaseInputs
from maingott_reel.utils.hashing import sha256_file

#: Provider names that mean "this was never really generated".
OFFLINE_PROVIDERS = ("fake",)

#: Stages a releasable run must have recorded.
REQUIRED_STAGES = (
    StageName.ANALYZE,
    StageName.PLAN,
    StageName.STORYBOARD,
    StageName.GENERATE_ASSETS,
    StageName.GENERATE_VOICE,
    StageName.COMPOSE,
    StageName.VALIDATE,
)


def _gate(
    name: str,
    passed: bool,
    detail: str | None = None,
    severity: GateSeverity = GateSeverity.ERROR,
) -> QualityGate:
    return QualityGate(
        name=name, group=GateGroup.RELEASE, passed=passed, detail=detail, severity=severity
    )


def production_gates(
    settings: Settings,
    inputs: ReleaseInputs,
    audit: QualityReport,
    registry: BrandRegistry | None,
    profile: VoiceProfile | None,
    fingerprint: ArtifactFingerprint,
    review: ReviewChecklist | None,
    approval: ApprovalRecord | None,
) -> list[QualityGate]:
    """Every check that stands between a valid Reel and a releasable one."""
    return [
        *_audit_gates(audit),
        *_pipeline_gates(inputs),
        *_footage_gates(inputs),
        *_voice_gates(inputs, profile),
        *_brand_gates(settings, inputs, registry),
        *_human_gates(fingerprint, review, approval),
    ]


def _audit_gates(audit: QualityReport) -> list[QualityGate]:
    """The Phase 6 audit has to pass on its own terms first."""
    blocking = audit.blocking_failures
    warnings = audit.warnings
    return [
        _gate(
            "quality_gates_pass",
            not blocking,
            f"{len(blocking)} blocking failure(s): " + ", ".join(gate.name for gate in blocking)
            if blocking
            else audit.summary(),
        ),
        _gate(
            "no_outstanding_warnings",
            not warnings,
            ", ".join(f"{gate.name} ({gate.detail})" for gate in warnings)
            if warnings
            else "nothing advisory is outstanding",
        ),
    ]


def _pipeline_gates(inputs: ReleaseInputs) -> list[QualityGate]:
    """The run has to be a complete, current pipeline run."""
    missing = [
        stage.value for stage in REQUIRED_STAGES if not inputs.manifest.stage_completed(stage)
    ]
    composition = inputs.composition
    return [
        _gate(
            "every_stage_completed",
            not missing,
            f"missing: {', '.join(missing)}" if missing else "analyze → validate",
        ),
        _gate(
            "not_a_development_composition",
            not composition.development,
            "the Reel was composed as a development output"
            if composition.development
            else "composed as a production output",
        ),
        _gate(
            "configuration_is_recorded",
            inputs.run.configuration_json.is_file(),
            str(inputs.run.configuration_json)
            if inputs.run.configuration_json.is_file()
            else "no configuration snapshot has been written for this run",
        ),
    ]


def _footage_gates(inputs: ReleaseInputs) -> list[QualityGate]:
    """Every scene has to be real generated footage."""
    assets = inputs.assets
    offline = assets.provider in OFFLINE_PROVIDERS
    placeholders = [asset.id for asset in assets.assets if asset.source is AssetSource.PLACEHOLDER]
    per_asset_offline = sorted(
        {asset.provider for asset in assets.assets if asset.provider in OFFLINE_PROVIDERS}
    )
    return [
        _gate(
            "footage_came_from_a_real_provider",
            not offline and not per_asset_offline,
            f"generated by {assets.provider}:{assets.model}"
            if not offline and not per_asset_offline
            else f"generated offline by {assets.provider}:{assets.model}",
        ),
        _gate(
            "no_placeholder_footage",
            not placeholders,
            f"placeholder clips: {', '.join(placeholders)}"
            if placeholders
            else f"{len(assets.assets)} generated clips",
        ),
    ]


def _voice_gates(inputs: ReleaseInputs, profile: VoiceProfile | None) -> list[QualityGate]:
    """The narration has to be a real voice, and the approved one."""
    audio = inputs.composition.audio
    voice = inputs.voice

    if audio.silent or audio.voice_path is None:
        return [
            _gate("narration_is_present", False, "the Reel has no narration"),
            _gate("narration_voice_is_approved", False, "there is no voice to approve"),
        ]

    gates = [
        _gate("narration_is_present", True, str(audio.voice_path)),
        _gate(
            "narration_came_from_a_real_provider",
            not audio.voice_is_development
            and (audio.voice_provider or "") not in OFFLINE_PROVIDERS,
            "the narration is a development placeholder, not a voice"
            if audio.voice_is_development or (audio.voice_provider or "") in OFFLINE_PROVIDERS
            else f"{audio.voice_provider}:{audio.voice_model}",
        ),
    ]

    if profile is None:
        gates.append(
            _gate(
                "narration_voice_is_approved",
                False,
                "no voice profile exists, so no voice has been approved",
            )
        )
        return gates
    if not profile.approved:
        gates.append(
            _gate(
                "narration_voice_is_approved",
                False,
                f"the voice profile for {profile.describe()} is not marked approved",
            )
        )
        return gates
    if voice is None:
        gates.append(
            _gate(
                "narration_voice_is_approved",
                False,
                "the narration was supplied from outside the pipeline, so it cannot be "
                "checked against the approved voice profile",
            )
        )
        return gates

    matches = profile.matches(voice.provider, voice.model, voice.voice, voice.language)
    gates.append(
        _gate(
            "narration_voice_is_approved",
            matches,
            f"approved: {profile.describe()}"
            if matches
            else f"spoken by {voice.provider}:{voice.model} voice '{voice.voice}' "
            f"({voice.language.value}), approved is {profile.describe()}",
        )
    )
    if profile.speed is not None:
        gates.append(
            _gate(
                "narration_speed_is_approved",
                voice.speed == profile.speed,
                f"spoken at {voice.speed}, approved is {profile.speed}",
            )
        )
    return gates


def _brand_gates(
    settings: Settings, inputs: ReleaseInputs, registry: BrandRegistry | None
) -> list[QualityGate]:
    """The brand mark, and any music, have to be approved assets."""
    logo = inputs.composition.logo
    logo_check = check_asset(
        registry,
        Path(logo.path) if logo else None,
        AssetType.IMAGE,
        sha256=logo.sha256 if logo else None,
    )
    gates = [
        _gate(
            "brand_registry_exists",
            registry is not None,
            str(settings.brand_registry_path)
            if registry is not None
            else f"no approved brand registry at {settings.brand_registry_path}",
        ),
        _gate("approved_logo_is_applied", logo_check.approved, logo_check.reason),
    ]

    music = inputs.composition.audio.music_path
    if settings.require_music:
        music_check = check_asset(
            registry,
            Path(music) if music else None,
            AssetType.MUSIC,
            sha256=inputs.composition.audio.music_sha256,
        )
        gates.append(_gate("approved_music_is_applied", music_check.approved, music_check.reason))
    elif music is not None:
        music_check = check_asset(
            registry, Path(music), AssetType.MUSIC, sha256=inputs.composition.audio.music_sha256
        )
        gates.append(
            _gate(
                "music_is_an_approved_asset",
                music_check.approved,
                music_check.reason,
                severity=GateSeverity.WARNING,
            )
        )
    return gates


def _human_gates(
    fingerprint: ArtifactFingerprint,
    review: ReviewChecklist | None,
    approval: ApprovalRecord | None,
) -> list[QualityGate]:
    """What a human has said about these exact bytes.

    These are reported, never required for candidacy: a release candidate is
    what a human is asked to review, so requiring the review first would be
    circular. ``approve`` is what enforces them.
    """
    if review is None:
        review_detail = "no human review has been started"
        reviewed = False
    elif review.final_sha256 != fingerprint.final_sha256:
        review_detail = "the review describes a different Reel"
        reviewed = False
    else:
        review_detail = review.summary()
        reviewed = review.complete

    if approval is None:
        approval_detail = "no human approval has been recorded"
        approved = False
    elif not approval.covers(fingerprint):
        approval_detail = "the approval describes different content: " + ", ".join(
            approval.fingerprint.differences(fingerprint)
        )
        approved = False
    elif not approval.approves:
        approval_detail = f"rejected by {approval.approved_by}"
        approved = False
    else:
        approval_detail = f"approved by {approval.approved_by} as {approval.release_version}"
        approved = True

    return [
        _gate("human_review_complete", reviewed, review_detail, severity=GateSeverity.WARNING),
        _gate("human_approval_recorded", approved, approval_detail, severity=GateSeverity.WARNING),
    ]


def audit_hash(path: Path) -> str:
    """Hash of an artifact, used when packaging a release."""
    return sha256_file(path)
