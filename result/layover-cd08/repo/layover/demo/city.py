"""Marnstadt, the worked example: a small city with six routes.

Everything in the documentation runs against this network, and so do the tests
that check a whole answer rather than one function. It is small enough to read
in one sitting and awkward enough to be interesting: a station with two
platforms and a walk between them, a ferry that only runs in the middle of the
day, an outer zone, and a public holiday that drops the weekday service.

Nothing here is generated by chance. The trips are laid out from a first departure, a last
departure and a headway, so the same call always builds the same network.
"""

