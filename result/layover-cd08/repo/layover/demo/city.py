def _calendars() -> ServiceRegistry:
    return ServiceRegistry(
        [
            ServiceCalendar.weekly(
                "weekday",
                ["mon", "tue", "wed", "thu", "fri"],
                DEMO_PERIOD,
                removed=[DEMO_HOLIDAY],
            ),
            ServiceCalendar.weekly("saturday", ["sat"], DEMO_PERIOD),
            ServiceCalendar.weekly(
                "sunday", ["sun"], DEMO_PERIOD, added=[DEMO_HOLIDAY]
            ),
        ]
    )


def _fares() -> FareTable:
    table = FareTable(currency="EUR")
    table.add_product(
        FareProduct("inner", Money("2.40"), transfers=2, window=5400, name="Inner city")
    )
    table.add_product(
        FareProduct("crossing", Money("3.60"), transfers=2, window=5400, name="City and outer")
    )
    table.add_product(
        FareProduct("outer", Money("2.00"), transfers=1, window=3600, name="Outer only")
    )
    table.add_product(
        FareProduct("ferry", Money("4.20"), transfers=0, window=3600, name="Ferry crossing")
    )
    table.add_rule(FareRule("ferry", route_id="f1"))
    table.add_rule(FareRule("inner", "A", "A"))
    table.add_rule(FareRule("crossing", "A", "B"))
    table.add_rule(FareRule("crossing", "B", "A"))
    table.add_rule(FareRule("outer", "B", "B"))
    return table


def _schedules_for(pattern_id: str) -> Tuple[tuple, ...]:
    return _FERRY_SCHEDULES if pattern_id.startswith("f1") else _SCHEDULES


def _trips(builder: NetworkBuilder) -> None:
    for pattern_id, _route, stops, headsign, _direction in _PATTERNS:
        hops = _HOPS[pattern_id]
        if len(hops) != len(stops) - 1:
            raise ValueError("pattern %r has the wrong number of hops" % pattern_id)
        for service_id, first, last, headway in _schedules_for(pattern_id):
            start = parse_clock(first) + _OFFSETS[pattern_id] % headway
            finish = parse_clock(last)
            number = 0
            while start <= finish:
                times: List[int] = [start]
                for hop in hops:
                    times.append(times[-1] + hop)
                builder.trip(
                    "%s-%s-%02d" % (pattern_id, service_id, number),
                    pattern_id,
                    service_id,
                    times,
                    headsign,
                )
                number += 1
                start += headway


def build_demo() -> FeedContents:
    """Build the demo network, its calendars and its fares from scratch."""
    builder = NetworkBuilder("Marnstadt")
    builder.add_stop(
        Stop(
            "hbf",
            "Hauptbahnhof",
            Point.of("53.552500", "9.964000"),
            None,
            StopKind.STATION,
            "A",
        )
    )
    for stop_id, name, lat, lon, zone in _STOPS:
        builder.stop(stop_id, name, lat, lon, zone=zone)
    for suffix, platform in (("u1", "1"), ("u2", "2")):
        builder.stop(
            "hbf-%s" % suffix,
            "Hauptbahnhof",
            "53.552500",
            "9.964000",
            parent="hbf",
            zone="A",
            platform=platform,
        )
    for route_id, short_name, long_name, mode, colour in _ROUTES:
        builder.add_route(Route(route_id, short_name, long_name, mode, "marnverkehr", colour))
    builder.add_agency(
        Agency(
            "marnverkehr",
            "Marnstadt Verkehr",
            "https://example.invalid/marnverkehr",
            "Europe/Berlin",
        )
    )
    for pattern_id, route_id, stops, headsign, direction in _PATTERNS:
        builder.pattern(pattern_id, route_id, list(stops), headsign, direction)
    _trips(builder)
    for from_stop, to_stop, seconds, kind in _TRANSFERS:
        builder.transfer(from_stop, to_stop, seconds, kind)
    return FeedContents(builder.build(), _calendars(), _fares(), "Marnstadt")


_CACHED: List[FeedContents] = []


def demo_contents() -> FeedContents:
    """The demo network, built once and shared.

    Everything it holds is immutable except the service registry, which is not
    added to anywhere in the package. Build a fresh one with :func:`build_demo`
    if that matters.
    """
    if not _CACHED:
        _CACHED.append(build_demo())
    return _CACHED[0]
